# The Bloomberg BQL service (`//blp/bqlsvc`) is licensed separately
# from BDP/BDH/BDS. On THIS firm's licence the central pool's classic
# API can't reach BQL, but the user's local Terminal IS authorized
# (via the Excel `@BQL` add-in path → also exposed to Python through
# matthewgilbert/blp). We use that as the primary BQL backend and
# only fall back to the central pool's POST endpoint when the local
# library is unavailable (e.g. running headless on a server).

_BLP_QUERY_SINGLETON: Any = None  # set to False when init has failed


def _get_local_blp_query():
    """Lazy-init module-level BlpQuery session.

    Cheaper to keep one session open across many BQL calls than to
    spin one up per request — the blpapi connect handshake takes
    ~300-500 ms locally. Sentinel `False` after a failed init so
    subsequent calls fast-path through to the central pool fallback.
    """
    global _BLP_QUERY_SINGLETON
    if _BLP_QUERY_SINGLETON is None:
        try:
            from blp import blp as _blp  # matthewgilbert/blp
            _BLP_QUERY_SINGLETON = _blp.BlpQuery().start()
            logger.info("Local BlpQuery (BQL) session started")
        except Exception as exc:
            logger.warning("Local BlpQuery init failed (%s) — BQL via "
                           "central pool fallback only", exc)
            _BLP_QUERY_SINGLETON = False
    return _BLP_QUERY_SINGLETON if _BLP_QUERY_SINGLETON else None


def _bql_get_for_with(expression: str, securities: list[str],
                      overrides: dict[str, str] | None) -> str:
    """Compose the full `get(...) for([...]) with(...)` BQL string
    from a bare expression. Pass-through if the caller already
    supplied a fully-formed BQL query."""
    expr = (expression or "").strip()
    if not expr:
        return ""
    if expr.lower().startswith("get("):
        return expr  # already complete
    sec_csv = ", ".join(f"'{s}'" for s in securities)
    with_clause = ""
    if overrides:
        kv = ", ".join(f"{k}={v}" for k, v in overrides.items())
        with_clause = f" with({kv})"
    return f"get({expr}) for([{sec_csv}]){with_clause}"


async def _async_bql(
    securities: list[str],
    expression: str,
    overrides: dict[str, str] | None = None,
) -> dict[str, Any]:
    """Run a single BQL expression and return {security: float|None}.

    Backend resolution:
      1. Local matthewgilbert/blp (preferred — direct blpapi to the
         on-machine Terminal, no central pool hop).
      2. Central pool POST /api/v1/bloomberg/bql (when the spec at
         docs/central_pool_bql_endpoint.md is deployed).
      3. Empty dict → caller falls back to BDP/BDH snapshot path.
    """
    if not securities or not expression:
        return {}

    full_expr = _bql_get_for_with(expression, securities, overrides)

    # ── Path 1: local blp ──────────────────────────────────────────
    bquery = _get_local_blp_query()
    if bquery is not None:
        def _run_sync():
            try:
                result = bquery.bql(expression=full_expr)
            except Exception as exc:
                logger.warning("Local BQL request failed (%s)", exc)
                return None
            if not result:
                return {}
            # blp returns a list of DataFrames; pull (id → value) off
            # the first frame. Multi-field BQL would return multiple
            # frames — for our use case (one scalar per security)
            # the first frame is sufficient.
            df = result[0]
            if not hasattr(df, "columns"):
                return {}
            cols = list(df.columns)
            if "id" not in cols or "value" not in cols:
                return {}
            import math
            out: dict[str, float | None] = {}
            for _, row in df.iterrows():
                sec = row["id"]
                v = row["value"]
                if v is None:
                    out[sec] = None; continue
                try:
                    fv = float(v)
                except (TypeError, ValueError):
                    out[sec] = None; continue
                # BQL emits NaN for cells where no contributor has
                # supplied an estimate. Treat as missing so callers
                # fall back to the BDP path or skip the row cleanly.
                out[sec] = None if math.isnan(fv) else fv
            return out
        try:
            res = await asyncio.to_thread(_run_sync)
        except Exception as exc:
            logger.warning("Local BQL thread failed (%s)", exc)
            res = None
        if res:  # non-empty dict = success
            return res

    # ── Path 2: central pool POST (fallback) ───────────────────────
    payload: dict[str, Any] = {
        "securities": securities,
        "expression": expression,
    }
    if overrides:
        payload["overrides"] = overrides
    try:
        data = await _post("/api/v1/bloomberg/bql", payload)
    except Exception as exc:
        logger.debug("Pool BQL endpoint unavailable (%s) — caller falls back",
                     exc)
        return {}
    if not isinstance(data, dict):
        return {}
    # Normalise the pool's response shape to {security: float|None}.
    out: dict[str, float | None] = {}
    for sec, raw in data.items():
        if raw is None:
            out[sec] = None; continue
        if isinstance(raw, (int, float)):
            out[sec] = float(raw); continue
        if isinstance(raw, dict):
            v = raw.get("value")
            out[sec] = float(v) if isinstance(v, (int, float)) else None
            continue
        if isinstance(raw, list):
            picked = None
            for row in raw:
                if isinstance(row, dict):
                    v = row.get("value")
                    if isinstance(v, (int, float)):
                        picked = float(v); break
            out[sec] = picked
            continue
        out[sec] = None
    return out


