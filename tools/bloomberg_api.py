def _summarise_payload(payload: dict) -> dict:
    """Condense a pool request payload into something short enough for UI display."""
    summary: dict[str, Any] = {}
    if "securities" in payload:
        secs = payload["securities"] or []
        summary["securities"] = secs[:5]
        if len(secs) > 5:
            summary["securities_total"] = len(secs)
    if "security" in payload:
        summary["security"] = payload["security"]
    if "field" in payload:
        summary["field"] = payload["field"]
    if "fields" in payload:
        flds = payload["fields"] or []
        summary["field_count"] = len(flds)
        summary["fields_sample"] = flds[:3]
    if "periodicity" in payload and payload["periodicity"]:
        summary["periodicity"] = payload["periodicity"]
    if "overrides" in payload and payload["overrides"]:
        summary["overrides"] = payload["overrides"]
    if "start_date" in payload:
        summary["start_date"] = payload.get("start_date")
    if "end_date" in payload:
        summary["end_date"] = payload.get("end_date")
    return summary


def _record_call(
    endpoint: str, payload: dict, elapsed_ms: float,
    agent_used: str | None, from_cache: bool,
    ok: bool, error: str | None = None,
) -> None:
    _call_history.append({
        "ts": datetime.now(timezone.utc).isoformat(),
        "endpoint": endpoint,
        "request": _summarise_payload(payload),
        "agent_used": agent_used,
        "from_cache": bool(from_cache),
        "elapsed_ms": round(elapsed_ms, 1),
        "ok": bool(ok),
        "error": (error or "")[:300] if error else None,
    })


def get_call_history(limit: int = 200) -> list[dict]:
    """Return the most recent N Bloomberg pool calls, newest first."""
    n = max(1, min(limit, CALL_HISTORY_CAP))
    items = list(_call_history)[-n:]
    return list(reversed(items))


def clear_call_history() -> int:
    n = len(_call_history)
    _call_history.clear()
    return n


def summarize_calls_since(since_iso: str) -> dict:
    """Return a compact summary of calls made since the given UTC ISO timestamp.

    Used at job-completion time so each analysis record carries a snapshot of
    which agent(s) served its Bloomberg data ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â mirrors the Risk Book
    "Last refreshed" chip. The summary is portable JSON suitable for storing
    on the analysis row.

    Shape:
      {
        "agents_used": ["SCKNG-D2", "SCKNg-N2"],   # distinct, order of first-seen
        "call_count": 14,                           # total calls during the job
        "ok_count": 12,
        "err_count": 2,
        "cache_hits": 3,
        "elapsed_ms_total": 18450.0,               # sum of round-trip times
        "endpoints": {"/api/v1/bloomberg/bdp": 7, "/api/v1/bloomberg/bdh": 4, ...},
      }
    """
    try:
        since_dt = datetime.fromisoformat(since_iso.replace("Z", "+00:00"))
        since_ts = since_dt.timestamp()
    except Exception:
        since_ts = 0.0

    agents_seen: list[str] = []
    call_count = 0
    ok_count = 0
    err_count = 0
    cache_hits = 0
    elapsed_total = 0.0
    endpoints: dict[str, int] = {}

    for c in _call_history:
        try:
            c_dt = datetime.fromisoformat(str(c.get("ts", "")).replace("Z", "+00:00"))
            if c_dt.timestamp() < since_ts:
                continue
        except Exception:
            continue
        call_count += 1
        if c.get("ok"):
            ok_count += 1
        else:
            err_count += 1
        if c.get("from_cache"):
            cache_hits += 1
        elapsed_total += float(c.get("elapsed_ms") or 0)
        agent = c.get("agent_used")
        if agent and agent not in agents_seen:
            agents_seen.append(agent)
        ep = c.get("endpoint")
        if ep:
            endpoints[ep] = endpoints.get(ep, 0) + 1

    return {
        "agents_used": agents_seen,
        "call_count": call_count,
        "ok_count": ok_count,
        "err_count": err_count,
        "cache_hits": cache_hits,
        "elapsed_ms_total": round(elapsed_total, 1),
        "endpoints": endpoints,
    }


# ── JCAP pool dispatcher ────────────────────────────────────────────────────
# Implements the data-agent pattern from HOW_TO_IMPLEMENT_BBG_DATA_AGENT.md §1:
# "If BBG runs on a different box, the codebase also supports an agent pool
#  over HTTPS (_post_pool) … with local DAPI as fallback — see _post()."
# Mirrors equity_swarm_V5/tools/bloomberg_api.py to keep the contract identical.

async def _post_pool(endpoint: str, payload: dict) -> Any:
    """Route a Bloomberg call through the JCAP pool (remote data agents)."""
    if httpx is None:
        raise RuntimeError("httpx not installed — required for JCAP pool calls")
    if not POOL_URL:
        raise RuntimeError("JCAP_POOL_URL is not configured")
    url = f"{POOL_URL}{endpoint}"
    headers = {"Authorization": f"Bearer {POOL_API_KEY}",
               "Content-Type": "application/json"}
    t0 = time.perf_counter()
    result: Any = None
    for attempt in (1, 2):
        try:
            async with httpx.AsyncClient(timeout=POOL_TIMEOUT) as client:
                resp = await client.post(url, json=payload, headers=headers)
                resp.raise_for_status()
                result = resp.json()
            break
        except (httpx.RemoteProtocolError, httpx.ConnectError) as exc:
            # Transient transport drop — retry ONCE. Timeouts/HTTP errors not retried.
            if attempt == 1:
                logger.debug("Pool %s transport error (%s) — retrying once", endpoint, exc)
                await asyncio.sleep(0.5)
                continue
            elapsed_ms = (time.perf_counter() - t0) * 1000
            err = f"{type(exc).__name__}: {exc!r}"
            _record_call(endpoint, payload, elapsed_ms, "pool", False,
                         ok=False, error=err)
            raise RuntimeError(f"JCAP pool {endpoint} failed: {err}")
        except Exception as exc:
            elapsed_ms = (time.perf_counter() - t0) * 1000
            err = f"{type(exc).__name__}: {exc!r}"
            _record_call(endpoint, payload, elapsed_ms, "pool", False,
                         ok=False, error=err)
            raise RuntimeError(f"JCAP pool {endpoint} failed: {err}")
    elapsed_ms = (time.perf_counter() - t0) * 1000
    agent_used = result.get("agent_used", "pool") if isinstance(result, dict) else "pool"
    _record_call(endpoint, payload, elapsed_ms, agent_used, False, ok=True)
    if isinstance(result, dict) and "data" in result:
        return result["data"]
    return result


def _is_local_dapi_port_open(host: str = "127.0.0.1", port: int = 8194,
                             timeout: float = 0.3) -> bool:
    """Cheap TCP probe — is the Bloomberg Terminal's DAPI socket listening?

    Used to skip the ~40-second blpapi session-start timeout when there's
    obviously no Terminal on this machine. Returns True only if a TCP
    connect succeeds within `timeout` seconds.
    """
    import socket as _sock
    try:
        with _sock.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


async def _post(endpoint: str, payload: dict) -> Any:
    """Dispatch a Bloomberg call: local DAPI first (when reachable), JCAP pool fallback.

    Follows HOW_TO_IMPLEMENT_BBG_DATA_AGENT.md §1: pool is the alternate
    path when no Terminal lives on this machine. We probe :8194 with a
    300ms TCP connect before invoking the local arm — if the port isn't
    open, skip straight to the pool. Avoids the multi-attempt blpapi
    session timeout (~40s) on Terminal-less hosts.

    Endpoints follow the canonical contract:
      /api/v1/bloomberg/bdp        → _xbbg_bdp
      /api/v1/bloomberg/bdh        → _xbbg_bdh
      /api/v1/bloomberg/bdp-bulk   → _xbbg_bds
    """
    local_exc: Exception | None = None
    # Probe the DAPI port OFF the event loop — _is_local_dapi_port_open() does a
    # blocking socket connect (~0.3s) that would otherwise stall the loop on
    # every dispatch (the module's whole point is to never block the loop).
    local_reachable = (_xbbg_blp is not None) and \
        await asyncio.to_thread(_is_local_dapi_port_open)
    if local_reachable:
        try:
            t0 = time.perf_counter()
            if endpoint == "/api/v1/bloomberg/bdp":
                data = await _xbbg_bdp(payload)
            elif endpoint == "/api/v1/bloomberg/bdh":
                data = await _xbbg_bdh(payload)
            elif endpoint == "/api/v1/bloomberg/bdp-bulk":
                data = await _xbbg_bds(payload)
            else:
                raise RuntimeError(f"Unknown Bloomberg endpoint: {endpoint}")
            elapsed_ms = (time.perf_counter() - t0) * 1000
            _record_call(endpoint, payload, elapsed_ms, "local", False, ok=True)
            return data
        except Exception as exc:
            local_exc = exc
            elapsed_ms = (time.perf_counter() - t0) * 1000
            _record_call(endpoint, payload, elapsed_ms, "local", False,
                         ok=False, error=str(exc))
            if not POOL_URL:
                raise
            logger.warning("Local Bloomberg DAPI failed (%s) — falling back to JCAP pool", exc)

    if POOL_URL:
        return await _post_pool(endpoint, payload)

    # Reached only when local DAPI was unreachable AND no pool is configured
    # (a local failure with no pool re-raises above, so local_exc is None here).
    raise RuntimeError(
        "Bloomberg unavailable: DAPI port 8194 not listening and JCAP_POOL_URL not set"
    )


