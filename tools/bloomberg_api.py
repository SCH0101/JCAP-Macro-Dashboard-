# ── In-process short-TTL cache for redundant BBG fetches ───────────
# Within a single swarm run (~2 minutes for one ticker), the same BBG
# call signature can fire from multiple call sites — e.g. once when
# `tools/ep_er_bbg_data.build_ep_data_blocks` assembles the LLM
# preface, then again when `generators/ep_tables.build_ep_tables`
# renders the deterministic numeric tables post-LLM. This cache makes
# the second call free. TTL is 5 minutes — long enough to span a
# swarm run + a quick re-run, short enough that intra-session BBG
# updates aren't masked. Keyed by (securities_tuple, fields_tuple,
# frozenset(overrides_items)).
import time as _time_cache

_BDP_CACHE: dict[tuple, tuple[float, dict]] = {}
_BDH_CACHE: dict[tuple, tuple[float, dict]] = {}
_BDP_CACHE_TTL_S = 300.0  # 5 minutes


def _cache_key(
    securities: list[str],
    fields: list[str],
    overrides: dict[str, str] | None,
) -> tuple:
    """Build a hashable signature for the BBG call."""
    secs = tuple(sorted(securities or []))
    flds = tuple(sorted(fields or []))
    ovr = frozenset((overrides or {}).items())
    return (secs, flds, ovr)


def _cache_get(cache: dict, key: tuple) -> dict | None:
    """Return cached result if present + within TTL; else None."""
    hit = cache.get(key)
    if not hit:
        return None
    ts, payload = hit
    if (_time_cache.monotonic() - ts) > _BDP_CACHE_TTL_S:
        cache.pop(key, None)
        return None
    return payload


def _cache_put(cache: dict, key: tuple, payload: dict) -> None:
    """Store payload with current timestamp. Best-effort eviction of
    expired entries to keep the dict bounded under heavy use."""
    now = _time_cache.monotonic()
    cache[key] = (now, payload)
    # Light opportunistic eviction — every ~100 inserts, drop expired.
    if len(cache) % 100 == 0:
        for k in [k for k, (ts, _) in cache.items()
                  if now - ts > _BDP_CACHE_TTL_S]:
            cache.pop(k, None)


async def _async_bdp_with_overrides(
    securities: list[str],
    fields: list[str],
    overrides: dict[str, str] | None = None,
) -> dict[str, dict[str, Any]]:
    """BDP wrapper that supports overrides. Returns {security: {FIELD: value, ...}}.

    Empty overrides are sent as empty dict (not None) so the central pool
    doesn't trip on a missing key.

    In-process cached for 5 minutes — see `_BDP_CACHE` above.
    """
    if not securities or not fields:
        return {}
    key = _cache_key(securities, fields, overrides)
    hit = _cache_get(_BDP_CACHE, key)
    if hit is not None:
        return hit
    payload = {"securities": securities, "fields": fields}
    if overrides:
        payload["overrides"] = overrides
    try:
        data = await _post("/api/v1/bloomberg/bdp", payload)
        result = data or {}
        _cache_put(_BDP_CACHE, key, result)
        return result
    except Exception as exc:
        logger.warning("BDP w/ overrides failed (%s): %s", fields, exc)
        return {}


