    # Canonical suffix words — title-case form is canonical. Added
    # 2026-05-14: previously this function passed through Bloomberg-style
    # inputs verbatim, so "ADYEN NA EQUITY" stayed all-caps and the rest
    # of the swarm (chart caches, peer-edit bootstrap, manual-segment
    # name matches) compared "ADYEN NA EQUITY" against "ADYEN NA Equity"
    # and silently failed, producing missing charts.
    _SUFFIX_CANON = {
        "equity": "Equity", "corp":  "Corp",  "index":  "Index",
        "curncy": "Curncy", "govt":  "Govt",  "mtge":   "Mtge",
        "muni":   "Muni",   "pfd":   "Pfd",   "comdty": "Comdty",
    }
    t = ticker.strip()
    if " " in t:
        # User passed a Bloomberg-style or partial-Bloomberg-style
        # ticker. Always re-canonicalize case so the rest of the swarm
        # sees ONE string per security.
        parts = t.split()
        last_word_canon = _SUFFIX_CANON.get(parts[-1].lower())
        if last_word_canon:
            head = parts[:-1]
            suffix_word = last_word_canon
        else:
            head = parts
            suffix_word = "Equity"  # default when suffix missing
        if len(head) >= 2:
            head[0] = head[0].upper()  # SYMBOL
            head[1] = head[1].upper()  # COUNTRY CODE
        elif len(head) == 1:
            # Symbol-only — uppercase. For Equity ONLY do we auto-inject
            # the "US" country code (the common analyst convenience —
            # paste "AAPL Equity", get "AAPL US Equity"). For Currency /
            # Index / Comdty / Govt / Curncy etc. the suffix carries its
            # own routing and a country code would be wrong:
            #   "EURUSD Curncy"  (NOT "EURUSD US Curncy")
            #   "SPX Index"      (NOT "SPX US Index")
            head[0] = head[0].upper()
            if suffix_word == "Equity":
                head.append("US")
        return f"{' '.join(head)} {suffix_word}"

