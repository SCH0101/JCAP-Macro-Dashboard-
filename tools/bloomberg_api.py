async def _async_is_bloomberg_available() -> bool:
    """Async availability probe ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â BDP a known-stable ticker via local DAPI."""
    global _bbg_available
    if _xbbg_blp is None:
        logger.warning("Bloomberg DAPI unavailable: xbbg/blpapi not installed (%s)", _XBBG_IMPORT_ERROR)
        _bbg_available = False
        return False
    try:
        data = await _post(
            "/api/v1/bloomberg/bdp",
            {"securities": ["SPY US Equity"], "fields": ["PX_LAST"]},
        )
        ok = isinstance(data, dict) and data.get("SPY US Equity") is not None
        _bbg_available = bool(ok)
    except Exception as exc:
        logger.warning("Local Bloomberg DAPI probe failed: %s", exc)
        _bbg_available = False
    return _bbg_available


