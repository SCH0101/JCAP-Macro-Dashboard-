# ── DAPI health check ───────────────────────────────────────────────
# xbbg silently returns empty DataFrames when the BBG session is
# blocked (WORKFLOW_REVIEW_NEEDED / monthly-limit). This raw-blpapi
# check detects the actual error code so the swarm can surface a
# clear message instead of producing blank charts/tables.

_HEALTH_CHECKED = False
_HEALTH_OK = True


def check_dapi_health() -> tuple[bool, str]:
    """One-shot raw blpapi health check. Returns (ok, message).

    Sends a single BDP request for SPX Index / PX_LAST. If Bloomberg
    responds with a LIMIT / WORKFLOW_REVIEW_NEEDED error, returns
    (False, <error message>). Caches the result so subsequent calls
    are free.
    """
    global _HEALTH_CHECKED, _HEALTH_OK
    if _HEALTH_CHECKED:
        return (_HEALTH_OK, "" if _HEALTH_OK else
                "Bloomberg DAPI blocked — workflow review needed on Terminal")
    _HEALTH_CHECKED = True
    try:
        import blpapi as _blpapi
    except ImportError:
        _HEALTH_OK = False
        return (False, "blpapi not installed")
    try:
        opts = _blpapi.SessionOptions()
        opts.setServerHost("localhost")
        opts.setServerPort(8194)
        sess = _blpapi.Session(opts)
        if not sess.start():
            _HEALTH_OK = False
            return (False, "Cannot start blpapi session — is Bloomberg Terminal running?")
        if not sess.openService("//blp/refdata"):
            sess.stop()
            _HEALTH_OK = False
            return (False, "Cannot open //blp/refdata service")
        svc = sess.getService("//blp/refdata")
        req = svc.createRequest("ReferenceDataRequest")
        req.append("securities", "SPX Index")
        req.append("fields", "PX_LAST")
        sess.sendRequest(req)
        error_msg = ""
        while True:
            ev = sess.nextEvent(8000)
            for msg in ev:
                if msg.hasElement("responseError"):
                    re = msg.getElement("responseError")
                    cat = str(re.getElementAsString("category")) if re.hasElement("category") else ""
                    sub = str(re.getElementAsString("subcategory")) if re.hasElement("subcategory") else ""
                    emsg = str(re.getElementAsString("message")) if re.hasElement("message") else ""
                    error_msg = f"Bloomberg DAPI blocked: {cat}/{sub} — {emsg.strip()}"
            if ev.eventType() == _blpapi.Event.RESPONSE:
                break
        sess.stop()
        if error_msg:
            _HEALTH_OK = False
            logger.critical(error_msg)
            return (False, error_msg)
        _HEALTH_OK = True
        return (True, "")
    except Exception as exc:
        _HEALTH_OK = False
        return (False, f"DAPI health check failed: {exc}")


