# xbbg 1.2 returns long-format DataFrames. The pool API the rest of the
# swarm consumes expects nested dicts. These helpers do the pivot.

def _bdp_long_to_pool_dict(df: Any, securities: list[str]) -> dict[str, dict[str, Any]]:
    """Convert xbbg BDP long DataFrame ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â ÃƒÂ¢Ã¢â€šÂ¬Ã¢â€žÂ¢ {security: {FIELD: value}}.

    Cells go through `_coerce_numeric` so '420.77' becomes 420.77, while
    legitimate strings (NAME, sector, EXPECTED_REPORT_DT) pass through.
    Without this every numeric field would arrive at downstream renderers
    as a string and blank out under format/compare/math operations.
    """
    nat = df.to_native() if hasattr(df, "to_native") else df
    out: dict[str, dict[str, Any]] = {sec: {} for sec in securities}
    if nat is None or len(nat) == 0:
        return out
    for rec in nat.to_dict(orient="records"):
        sec = rec.get("ticker")
        fld = rec.get("field")
        if not sec or not fld:
            continue
        # Normalize to UPPERCASE — xbbg long-format emits lowercase
        # mnemonics; consumers read by uppercase BBG mnemonic (PX_LAST).
        out.setdefault(sec, {})[str(fld).upper()] = _coerce_numeric(rec.get("value"))
    return out


def _bdh_long_to_pool_dict(df: Any) -> dict[str, list[dict[str, Any]]]:
    """Convert xbbg BDH long DataFrame ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â ÃƒÂ¢Ã¢â€šÂ¬Ã¢â€žÂ¢ {security: [{date, FIELD1, ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬Ãƒâ€šÃ‚Â¦}, ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬Ãƒâ€šÃ‚Â¦]}.

    Pivots field names so each output row holds all field values for one
    (security, date), matching the pool BDH response shape exactly.
    """
    nat = df.to_native() if hasattr(df, "to_native") else df
    out: dict[str, list[dict[str, Any]]] = {}
    if nat is None or len(nat) == 0:
        return out
    bucket: dict[tuple[str, str], dict[str, Any]] = {}
    order: list[tuple[str, str]] = []
    for rec in nat.to_dict(orient="records"):
        sec = rec.get("ticker")
        date = rec.get("date")
        fld = rec.get("field")
        val = rec.get("value")
        if not sec or date is None or not fld:
            continue
        date_str = str(date)[:10]
        key = (sec, date_str)
        if key not in bucket:
            bucket[key] = {"date": date_str}
            order.append(key)
        # Normalize to UPPERCASE — xbbg long-format emits lowercase
        # mnemonics; consumers read by uppercase BBG mnemonic (PX_LAST).
        bucket[key][str(fld).upper()] = _coerce_numeric(val)
    for sec, _date in order:
        out.setdefault(sec, []).append(bucket[(sec, _date)])
    for sec in out:
        out[sec].sort(key=lambda r: r.get("date", ""))
    return out


def _bds_long_to_pool_list(df: Any) -> list[dict[str, Any]]:
    """Convert xbbg BDS long DataFrame ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â ÃƒÂ¢Ã¢â€šÂ¬Ã¢â€žÂ¢ list[row_dict].

    Pool's bdp-bulk returns one record per BDS row with arbitrary
    field-specific columns. We drop the synthetic `ticker` and `field`
    cols xbbg adds and pass the rest through unchanged.

    NOTE: xbbg BDS columns frequently contain spaces (e.g. 'Metric
    Name', 'Hierarchy Level', 'Period 1 Value'). itertuples() renames
    those to positional `_1`/`_2`/... ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â `getattr(row, 'Metric Name')`
    raises AttributeError. We use to_dict(orient='records') to
    preserve original column names verbatim.
    """
    nat = df.to_native() if hasattr(df, "to_native") else df
    if nat is None or len(nat) == 0:
        return []
    drop = {"ticker", "field"}
    rows: list[dict[str, Any]] = []
    for rec_in in nat.to_dict(orient="records"):
        rec = {k: _coerce_numeric(v) for k, v in rec_in.items() if k not in drop}
        rows.append(rec)
    return rows


# Map "frequency" enum the pool callers used ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â€šÂ¬Ã‚Â ÃƒÂ¢Ã¢â€šÂ¬Ã¢â€žÂ¢ xbbg `Per` argument.
_FREQ_TO_XBBG = {
    "DAILY": "D", "WEEKLY": "W", "MONTHLY": "M",
    "QUARTERLY": "Q", "SEMI_ANNUALLY": "S", "YEARLY": "Y",
}


async def _xbbg_bdp(payload: dict) -> dict[str, dict[str, Any]]:
    securities = list(payload.get("securities") or [])
    fields = list(payload.get("fields") or [])
    overrides = payload.get("overrides") or {}
    if not securities or not fields:
        return {}
    kwargs: dict[str, Any] = {}
    if overrides:
        kwargs.update({str(k): v for k, v in overrides.items()})
    kwargs.setdefault("format", "long")  # avoid duplicate-kw TypeError if an override sets 'format'
    df = await asyncio.to_thread(
        _xbbg_blp.bdp, securities, fields, **kwargs,
    )
    return _bdp_long_to_pool_dict(df, securities)


async def _xbbg_bdh(payload: dict) -> dict[str, list[dict[str, Any]]]:
    securities = list(payload.get("securities") or [])
    fields = list(payload.get("fields") or [])
    start_date = payload.get("start_date")
    end_date = payload.get("end_date") or ""
    periodicity = (payload.get("periodicity") or "DAILY").upper()
    overrides = payload.get("overrides") or {}
    if not securities or not fields or not start_date:
        return {}
    per = _FREQ_TO_XBBG.get(periodicity, "D")
    kwargs: dict[str, Any] = {"Per": per}
    if overrides:
        kwargs.update({str(k): v for k, v in overrides.items()})
    kwargs.setdefault("format", "long")  # avoid duplicate-kw TypeError if an override sets 'format'
    df = await asyncio.to_thread(
        _xbbg_blp.bdh, securities, fields, start_date, end_date, **kwargs,
    )
    return _bdh_long_to_pool_dict(df)


async def _xbbg_bds(payload: dict) -> list[dict[str, Any]]:
    security = payload.get("security")
    field = payload.get("field")
    overrides = payload.get("overrides") or {}
    if not security or not field:
        return []
    kwargs: dict[str, Any] = {}
    if overrides:
        kwargs.update({str(k): v for k, v in overrides.items()})
    # NOTE: this xbbg version's `bds` does NOT accept a `format` kwarg —
    # it forwards unknown kwargs to Bloomberg as overrides, which rejects
    # it ("Invalid argument: element 'format' not found") and the whole
    # BDS call fails. The default bds output is ALREADY long-format
    # (columns: ticker, field, <data cols>) — exactly what
    # _bds_long_to_pool_list expects — so `format="long"` was both
    # redundant and fatal. `bdp`/`bdh` DO accept `format` (left intact).
    df = await asyncio.to_thread(
        _xbbg_blp.bds, security, field, **kwargs,
    )
    return _bds_long_to_pool_list(df)


